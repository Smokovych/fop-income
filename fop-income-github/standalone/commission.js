// ============================================================ комісія еквайрингу
// Шукає в призначенні платежу суму утриманої комісії банку. Повертає копійки (0 — не знайдено).
// Приклади: «комісія 13,00 грн», «ком. банку 26.50», «Ком.бан. 1 250,00», «комісія 1,3% - 13,00 грн»,
// «утримана комісія: 7.15», «13,00 грн комісії», «commission 5.20».
const COMM_WORD = "(?<!без\\s{1,3})(?<!no\\s)(?:к[оo]м[iі1]с[iі1][яїюйе]\\S*|к[оo]м[iі]с\\.?|ком\\s*\\.\\s*(?:банк\\S*|бан\\.?)?|ком\\s+бан\\S*|комісійн\\S*|commission\\S*|comission\\S*)";
const COMM_NUM = "(\\d{1,3}(?:[ \\u00a0]\\d{3})+(?:[.,]\\d{1,2})?|\\d+(?:[.,]\\d{1,2})?)";
const COMM_RX_AFTER = new RegExp(
  COMM_WORD + "[^\\d%]{0,40}?" +                    // слово «комісія» + до 40 символів (банку, утримана, :, = …)
  "(?:\\d+(?:[.,]\\d+)?\\s*%[^\\d]{0,20}?)?" +       // необов'язковий відсоток: «1,3% - »
  COMM_NUM + "(?![.,]?\\d)(?!\\s*%)", "i");
const COMM_RX_BEFORE = new RegExp(COMM_NUM + "(?![.,]?\\d)\\s*(?:грн\\.?|uah)?\\s*[-–—]?\\s*" + COMM_WORD, "i");

function parseCommission(text) {
  const s = String(text || "").replace(/ /g, " ");
  const m = s.match(COMM_RX_AFTER) || s.match(COMM_RX_BEFORE);
  if (!m) return 0;
  const v = Number(m[1].replace(/\s/g, "").replace(",", "."));
  return isFinite(v) && v > 0 ? Math.round(v * 100) : 0;
}
